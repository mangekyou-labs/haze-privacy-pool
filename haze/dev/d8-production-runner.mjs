const ROOT = dirname(fileURLToPath(import.meta.url));
export const OUTPUT_DIR = join(ROOT, "../output/playwright");

export function planD8ProductionJourney(input = {}) {
  const productionUrl = input.productionUrl ?? PRODUCTION_URL;
  if (
    !productionUrl ||
    productionUrl.includes("localhost") ||
    productionUrl.includes("127.0.0.1") ||
    productionUrl.includes("preview")
  ) {
    throw Object.assign(new Error(`Production origin ${PRODUCTION_URL} is required for D8 acceptance`), {
      code: "PRODUCTION_ORIGIN_REQUIRED",
    });
  }

  const runner = input.runner ?? "playwright-cli";
  if (runner !== "playwright-cli") {
    throw Object.assign(new Error("Actual named playwright-cli session is required; playwright-core is refused"), {
      code: "PLAYWRIGHT_CLI_REQUIRED",
    });
  }

  if (input.fixedHash) {
    throw Object.assign(new Error("Fresh Fuji transaction hash generated by the run is required; fixed seeded hash is refused"), {
      code: "FRESH_HASH_REQUIRED",
    });
  }

  return {
    ok: true,
    productionUrl,
    chainId: input.chainId ?? FUJI_CHAIN_ID,
    runner,
    walletSteps: [
      "connect_operator",
      "deposit_1_usdc",
      "verify_deposit_receipt",
      "reload_verify_note_recovery",
      "withdraw_same_note",
      "verify_withdraw_receipt",
      "stop_chain_transactions",
      "auditor_siwe_auth",
      "assert_auditor_tx_count_unchanged",
    ],
    portalSteps: [
      "load_auditor_session",
      "open_production_audit",
      "verify_origin_and_chain",
      "assert_only_same_origin_traffic",
      "wait_ingested_case_matching_fresh_withdraw",
      "observe_confirmations_to_12",
      "verify_and_disclose",
      "assert_integrity_and_5_fields",
      "assert_no_identity_leaks",
      "export_review_download_verify_signature",
      "verify_access_history_and_hash_chain",
      "mobile_390x844_no_overflow",
      "logout_assert_data_cleared",
      "fail_closed_unauthenticated_and_admin_governance",
    ],
  };
}

export function writeJourneyManifest(manifest, outDir = OUTPUT_DIR) {
  mkdirSync(outDir, { recursive: true });
  const manifestPath = join(outDir, "d8-production-journey-manifest.json");
  writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + "\n");
  return manifestPath;
}

